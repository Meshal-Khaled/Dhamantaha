// Creates or updates infrastructure/.env on The Ring: asks for the Gemini key
// (hidden) and model, generates app client keys, and writes the file readable
// only by its owner. Re-running keeps existing values when you press Enter.
//
// Usage: npm run setup [-- --new-client-keys] [--file <path>]
import { randomBytes } from 'node:crypto';
import { chmod, readFile, rename, writeFile } from 'node:fs/promises';
import { createInterface } from 'node:readline/promises';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';

const { values: flags } = parseArgs({
  options: {
    file: { type: 'string', default: fileURLToPath(new URL('../.env', import.meta.url)) },
    'new-client-keys': { type: 'boolean', default: false },
  },
});

const CLIENT_KEY_NAMES = ['android', 'web-test'];

/** Settings for The Ring behind a Cloudflare Tunnel. */
const RING_DEFAULTS = {
  HOST: '127.0.0.1',
  PORT: '3100',
  // cloudflared reaches the container through loopback or the Docker bridge; trusting
  // those hops lets per-IP limits see each phone's real address.
  TRUST_PROXY: 'loopback,uniquelocal',
  CORS_ORIGINS: 'https://localhost',
  ENABLE_API_DOCS: 'true',
  LOG_LEVEL: 'info',
  WALLET_TIME_ZONE: 'Asia/Riyadh',
  ANALYSIS_PROVIDER: 'gemini',
  // Cloudflare ends requests after 100 s; a PDF can need two Gemini calls.
  GEMINI_TIMEOUT_MS: '40000',
  MAX_IMAGE_BYTES: '20971520',
  MAX_PDF_BYTES: '10485760',
  MAX_PDF_PAGES: '10',
  MAX_IMAGE_PIXELS: '50000000',
  IMAGE_MAX_DIMENSION: '3072',
  MAX_CONCURRENT_ANALYSES: '4',
  RATE_LIMIT_PER_MINUTE: '10',
  DAILY_PROVIDER_CALL_LIMIT: '500',
};

const SECTIONS = [
  ['Server', ['HOST', 'PORT', 'TRUST_PROXY', 'CORS_ORIGINS', 'ENABLE_API_DOCS', 'LOG_LEVEL', 'WALLET_TIME_ZONE']],
  ['App access (send one of these as X-Client-Key)', ['CLIENT_KEYS']],
  ['Analysis provider', ['ANALYSIS_PROVIDER', 'GEMINI_API_KEY', 'GEMINI_MODEL', 'GEMINI_TIMEOUT_MS']],
  [
    'Limits',
    [
      'MAX_IMAGE_BYTES',
      'MAX_PDF_BYTES',
      'MAX_PDF_PAGES',
      'MAX_IMAGE_PIXELS',
      'IMAGE_MAX_DIMENSION',
      'MAX_CONCURRENT_ANALYSES',
      'RATE_LIMIT_PER_MINUTE',
      'DAILY_PROVIDER_CALL_LIMIT',
    ],
  ],
];

function parseEnv(text) {
  const entries = new Map();
  for (const line of text.split(/\r?\n/)) {
    const match = /^\s*([A-Z0-9_]+)\s*=\s*(.*)$/.exec(line);
    if (match) entries.set(match[1], match[2].trim().replace(/^(['"])(.*)\1$/, '$2'));
  }
  return entries;
}

function renderEnv(settings) {
  const known = new Set(SECTIONS.flatMap(([, keys]) => keys));
  const lines = [
    `# Generated by "npm run setup" on ${new Date().toISOString().slice(0, 10)}.`,
    '# Private: readable only by its owner. Never commit, copy into the app, or share this file.',
  ];
  for (const [title, keys] of SECTIONS) {
    lines.push('', `# --- ${title} ---`, ...keys.map((key) => `${key}=${settings.get(key) ?? ''}`));
  }
  const others = [...settings].filter(([key]) => !known.has(key));
  if (others.length) lines.push('', '# --- Other settings ---', ...others.map(([key, value]) => `${key}=${value}`));
  return `${lines.join('\n')}\n`;
}

/**
 * Prompts on a terminal (hidden input for secrets). When input is piped, it
 * reads one line per question instead, so the script can run unattended.
 */
async function createPrompter() {
  if (!process.stdin.isTTY) {
    const chunks = [];
    for await (const chunk of process.stdin) chunks.push(chunk);
    const lines = Buffer.concat(chunks).toString('utf8').split(/\r?\n/);
    return {
      ask: async (question) => {
        process.stdout.write(`${question}\n`);
        return (lines.shift() ?? '').trim();
      },
    };
  }

  const askVisible = async (question) => {
    const rl = createInterface({ input: process.stdin, output: process.stdout });
    try {
      return (await rl.question(question)).trim();
    } finally {
      rl.close();
    }
  };

  const askHidden = (question) =>
    new Promise((resolve, reject) => {
      const { stdin } = process;
      let value = '';
      const finish = (result, error) => {
        stdin.off('data', onData);
        stdin.setRawMode(false);
        stdin.pause();
        process.stdout.write('\n');
        if (error) reject(error);
        else resolve(result.trim());
      };
      const onData = (chunk) => {
        for (const ch of chunk) {
          if (ch === '\r' || ch === '\n') return finish(value);
          if (ch === '\u0003') return finish('', new Error('Cancelled.'));
          if (ch === '\u007f' || ch === '\b') value = value.slice(0, -1);
          else value += ch;
        }
      };
      process.stdout.write(question);
      stdin.setRawMode(true);
      stdin.setEncoding('utf8');
      stdin.resume();
      stdin.on('data', onData);
    });

  return { ask: (question, { hidden = false } = {}) => (hidden ? askHidden(question) : askVisible(question)) };
}

async function main() {
  let existing = new Map();
  try {
    existing = parseEnv(await readFile(flags.file, 'utf8'));
    console.log(`Updating ${flags.file}. Press Enter to keep a current value.`);
  } catch (err) {
    if (err.code !== 'ENOENT') throw err;
    console.log(`Creating ${flags.file}.`);
  }

  const settings = new Map(Object.entries(RING_DEFAULTS));
  for (const [key, value] of existing) settings.set(key, value);

  const prompter = await createPrompter();
  const hasKey = Boolean(existing.get('GEMINI_API_KEY'));
  const apiKey = await prompter.ask(`Gemini API key${hasKey ? ' [keep current]' : ''}: `, { hidden: true });
  if (apiKey) settings.set('GEMINI_API_KEY', apiKey);
  if (!settings.get('GEMINI_API_KEY')) throw new Error('A Gemini API key is required. Create one in Google AI Studio.');

  const currentModel = settings.get('GEMINI_MODEL');
  const model = await prompter.ask(`Gemini model ID${currentModel ? ` [${currentModel}]` : ''}: `);
  if (model) settings.set('GEMINI_MODEL', model);
  if (!settings.get('GEMINI_MODEL')) {
    throw new Error('A Gemini model ID is required; see https://ai.google.dev/gemini-api/docs/models.');
  }
  settings.set('ANALYSIS_PROVIDER', 'gemini');

  let newClientKeys = null;
  if (flags['new-client-keys'] || !settings.get('CLIENT_KEYS')) {
    newClientKeys = CLIENT_KEY_NAMES.map((name) => ({ name, key: randomBytes(24).toString('base64url') }));
    settings.set('CLIENT_KEYS', newClientKeys.map(({ name, key }) => `${name}:${key}`).join(','));
  }

  const temporary = `${flags.file}.tmp`;
  await writeFile(temporary, renderEnv(settings), { mode: 0o600 });
  await rename(temporary, flags.file);
  await chmod(flags.file, 0o600);

  console.log(`\nSaved ${flags.file} (owner read/write only).`);
  console.log(`Gemini model: ${settings.get('GEMINI_MODEL')} · key: saved, not shown`);
  if (newClientKeys) {
    console.log('\nNew app keys (send as the X-Client-Key header). Store them in a password manager;');
    console.log('the app key goes into the Android build config, never into Git:');
    for (const { name, key } of newClientKeys) console.log(`  ${name.padEnd(9)} ${key}`);
  } else {
    console.log('App keys unchanged (CLIENT_KEYS in the file). Use --new-client-keys to replace them.');
  }
  console.log('\nApply the changes:  docker compose up -d --force-recreate');
}

main().catch((err) => {
  console.error(`Setup failed: ${err.message}`);
  process.exit(1);
});
